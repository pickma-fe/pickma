function createMockDateTime(time: string) {
  const [hour, minute] = time.split(':').map(Number);
  const today = new Date();

  return new Date(
    today.getFullYear(),
    today.getMonth(),
    today.getDate(),
    hour,
    minute,
    0,
    0
  ).toISOString();
}

